// Шаблоны запросов к ИИ. Единый источник: используются и во встроенном режиме,
// и в режиме «скопировать промпт в любой чат» (DeepSeek, GigaChat, Алиса…).
window.PROMPTS = (() => {
  const SYSTEM =
    "Ты – методист и учитель математики российской школы, курс «Вероятность и статистика» (ФГОС, 7–11 классы). " +
    "Пиши по-русски, на уровне указанного класса, без высшей математики. " +
    "Все вероятности и числа пересчитывай дважды. Если не уверен в ответе – прямо так и напиши. " +
    "Твой результат – черновик: его проверит учитель. Тире пиши коротким знаком «–», а не длинным.";

  const KINDS = {
    analog:     { title: "Аналоги",               hint: "Новые задачи с той же целью и той же типичной ошибкой, но другим сюжетом", multi: true },
    diagnostic: { title: "Диагностические",       hint: "Задачи, где типичная ошибка ученика даёт конкретный неверный ответ", multi: true },
    solution:   { title: "Решение",               hint: "Подробное решение для ученика этого класса" },
    comments:   { title: "Методические комментарии", hint: "Черновики комментариев всех шести типов" },
    check:      { title: "Проверить решение",     hint: "ИИ решает сам и сравнивает с решением из банка" },
  };

  function context(t, withContext) {
    let s = `Исходная задача (${t.grade} класс, раздел «${t.section}», тема «${t.topic}», сложность ${t.difficulty} из 5):\n${t.condition}\n`;
    if (!withContext) return s;
    if (t.solution) s += `\nРешение из банка задач:\n${t.solution}\n`;
    if (t.answer) s += `Ответ: ${t.answer}\n`;
    if (t.comments.length) {
      s += "\nМетодические комментарии учителей к этой задаче:\n";
      for (const c of t.comments) s += `– ${c.type}: ${c.body}\n`;
    }
    return s;
  }

  function build(kind, t, withContext, count) {
    const ctx = context(t, withContext);
    const trap = withContext ? (t.comments.find((c) => c.type === "Частая ошибка ученика") || {}).body : null;
    const trapText = trap ? ` (типичная ошибка: «${trap}»)` : "";
    switch (kind) {
      case "analog": return `${ctx}
Составь ${count} новые задачи-аналога для ${t.grade} класса той же сложности.
Требования:
1. Проверяется то же умение и та же типичная ошибка ученика${trapText}.
2. Другой сюжет из жизни школьника (не монета и не кость, если они были в исходной).
3. Числа подобраны так, чтобы ответ был «красивым».
Для каждой задачи дай: условие; решение; краткий ответ; какую ошибку ученика она выявляет.
Ответ верни строго в JSON: {"tasks":[{"condition":"","solution":"","answer":"","trap":""}]}`;
      case "diagnostic": return `${ctx}
Составь ${count} диагностические задачи для ${t.grade} класса: такие, чтобы ученик с типичной ошибкой${trapText} получил конкретный НЕВЕРНЫЙ ответ, отличный от верного.
Для каждой дай: условие; верное решение; верный ответ; неверный ответ, который получится при ошибке, и почему.
Ответ верни строго в JSON: {"tasks":[{"condition":"","solution":"","answer":"","wrong_answer":"","trap":""}]}`;
      case "solution": return `${ctx}
Напиши подробное решение этой задачи так, как его объяснил бы учитель ученику ${t.grade} класса, и краткий ответ.
Ответ верни строго в JSON: {"solution":"","answer":""}`;
      case "comments": return `${ctx}
Предложи методические комментарии для учителя к этой задаче – по одному каждого типа:
«Жизненный пример», «Историческая справка» (только достоверные факты; если не уверен – пропусти), «Методическая справка», «Частая ошибка ученика», «Возможный вопрос» (что может спросить ученик и как ответить), «Вопрос для ученика».
Ответ верни строго в JSON: {"comments":[{"type":"","body":""}]}`;
      case "check": return `${ctx}
Проверь решение и ответ из банка задач. Реши задачу самостоятельно, затем сравни.
Если в решении есть ошибка или неточность – укажи её и дай исправленный вариант.
Ответ верни строго в JSON: {"correct":true,"issues":"","fixed_solution":"","fixed_answer":""}`;
    }
    throw new Error("Неизвестный вид запроса: " + kind);
  }

  // Достаёт JSON из ответа модели (модели любят обрамлять его текстом и ```)
  function parse(text) {
    if (!text) return null;
    const cleaned = text.replace(/```(?:json)?/gi, "");
    const start = cleaned.indexOf("{"), end = cleaned.lastIndexOf("}");
    if (start < 0 || end <= start) return null;
    try { return JSON.parse(cleaned.slice(start, end + 1)); } catch { return null; }
  }

  return { SYSTEM, KINDS, build, parse };
})();
